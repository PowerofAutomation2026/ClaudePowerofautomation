// Minimal "chat with a Copilot Studio agent" helper for a Power Apps code app.
// Needs: the custom connector "SPX Copilot Direct" added to the app (see README, "Add the connector to a new code app").
// Copy this file into your app (e.g. src/copilotDirect.ts) and call askAgent(...).
import { getClient } from '@microsoft/power-apps/data'
import { dataSourcesInfo } from '../.power/schemas/appschemas/dataSourcesInfo'   // generated by `pac code add-data-source`

const client = getClient(dataSourcesInfo as any)

/** the key under which pac registered the custom connector (it has Discover + Path4..Path12 operations) */
const connectorKey = Object.keys(dataSourcesInfo as any).find((k) => {
  const ops = Object.keys((dataSourcesInfo as any)[k]?.apis ?? {})
  return ops.includes('Discover') && ops.some((o) => /^Path\d+$/.test(o))
})

/** environment GUID -> nothing to compute here: the connector's host already points at your environment */
async function call(operationName: string, parameters: Record<string, unknown>): Promise<string> {
  if (!connectorKey) throw new Error('The SPX Copilot Direct connector is not added to this app (run: pac code add-data-source -a <apiName> -c <connectionId>).')
  const res: any = await client.executeAsync({ connectorOperation: { tableName: connectorKey, operationName, parameters } } as any)
  if (!res?.success) throw new Error(String(res?.error?.message ?? JSON.stringify(res?.error ?? 'The call failed')))
  const d = res.data
  return typeof d === 'string' ? d : typeof d?.body === 'string' ? d.body : JSON.stringify(d?.body ?? d ?? '')
}

/** POST to a full URL that Copilot Studio gave us: every path segment becomes s1, s2, ... (so slashes stay slashes) */
function post(url: string, body: unknown): Promise<string> {
  const u = new URL(url)
  const segs = u.pathname.split('/').filter(Boolean).map(decodeURIComponent)
  const params: Record<string, unknown> = { body }
  segs.forEach((s, i) => { params[`s${i + 1}`] = s })
  const v = u.searchParams.get('api-version'); if (v) params['api-version'] = v
  return call(`Path${segs.length}`, params)
}

/** answers come back as server-sent events ("data: {...}") or plain JSON: collect the activities */
function activities(text: string): any[] {
  const out: any[] = []
  for (const block of text.split(/\r?\n\r?\n/)) {
    const data = block.split(/\r?\n/).filter((l) => l.startsWith('data:')).map((l) => l.slice(5).trim()).join('')
    if (!data) continue
    try { const j = JSON.parse(data); out.push(...(Array.isArray(j) ? j : [j.activity ?? j])) } catch { /* ignore */ }
  }
  if (!out.length) { try { const j = JSON.parse(text); out.push(...(Array.isArray(j) ? j : j.activities ?? [j])) } catch { /* ignore */ } }
  return out
}

/**
 * Ask a published Copilot Studio agent (new experience or classic).
 * agentSchema = Copilot Studio -> agent -> Settings -> Advanced -> Metadata -> Schema name (case-sensitive)
 * Pass the returned conversationId back in to continue the same chat.
 */
export async function askAgent(agentSchema: string, message: string, conversationId?: string) {
  // 1) ask Copilot Studio where this agent's conversation endpoints are
  const found = JSON.parse(await call('Discover', { agent: agentSchema }))
  const createUrl: string = found.createConversation ?? found.conversations
  const turnUrl: string = found.executeTurn ?? found.turn
  // 2) start a conversation (first message only)
  let id = conversationId
  if (!id) {
    const start = activities(await post(createUrl, { emitStartConversationEvent: true }))
    id = start.map((a) => a?.conversation?.id).find(Boolean)
    if (!id) throw new Error('No conversation id returned - is the agent published?')
  }
  // 3) send the message and read the reply
  const url = turnUrl.replace(/\{conversationId\}/gi, encodeURIComponent(id))
  const acts = activities(await post(url, { activity: { type: 'message', text: message, conversation: { id } }, conversationId: id }))
  const text = acts.filter((a) => a?.type === 'message' && a.text).map((a) => String(a.text)).pop() ?? ''
  return { text, conversationId: id }
}
